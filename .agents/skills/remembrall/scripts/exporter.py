#!/usr/bin/env python3
"""
Remembrall Exporter Module.
Transforms .remembrall.md into production changelogs, GitHub Issues commands, and release notes.
"""

import datetime
import json
import sys
from pathlib import Path

# Add scripts directory
SCRIPT_DIR = Path(__file__).parent.resolve()
if str(SCRIPT_DIR) not in sys.path:
    sys.path.insert(0, str(SCRIPT_DIR))

import remembrall


def export_changelog(manifest_path, version="1.0.0"):
    features = remembrall.parse_features(manifest_path)
    today = datetime.date.today().isoformat()
    
    done_features = [f for f in features.values() if f["status"] == "DONE"]
    
    lines = [
        "# Changelog",
        "All notable changes to this project are documented automatically via Remembrall.\n",
        f"## [{version}] - {today}",
        "### Added"
    ]
    
    for f in done_features:
        notes = f" - {f['notes']}" if f["notes"] else ""
        lines.append(f"- **{f['title']}** (`{f['files']}`){notes}")
        
    return "\n".join(lines) + "\n"


def export_github_issues(manifest_path):
    features = remembrall.parse_features(manifest_path)
    lines = ["# GitHub CLI Issue Creation Script", "# Run the following commands to create GitHub issues:\n"]
    
    for f in features.values():
        title = f"[{f['id']}] {f['title']}"
        body = f"Status: {f['status']}\\nPrimary Files: {f['files']}"
        if f["notes"]:
            body += f"\\nNotes: {f['notes']}"
            
        label = "enhancement" if f["status"] == "PLANNED" else "in-progress" if f["status"] == "WIP" else "completed"
        cmd = f'gh issue create --title "{title}" --body "{body}" --label "{label}"'
        lines.append(cmd)
        
    return "\n".join(lines) + "\n"


def export_release_notes(manifest_path, tag="v1.0.0"):
    features = remembrall.parse_features(manifest_path)
    done_features = [f for f in features.values() if f["status"] == "DONE"]
    
    lines = [
        f"## 🚀 Release {tag}",
        "Automated release notes generated by Remembrall State Engine.\n",
        "### 📦 Included Features & Changes:"
    ]
    
    for f in done_features:
        lines.append(f"- `[{f['id']}]` **{f['title']}**")
        lines.append(f"  - Key files: `{f['files']}`")
        if f["notes"]:
            lines.append(f"  - Note: {f['notes']}")
            
    lines.append("\n*Generated with ❤️ by Remembrall Zero-Amnesia AI Engine.*")
    return "\n".join(lines) + "\n"


def export_json(manifest_path):
    stats = remembrall.get_stats(manifest_path)
    features = remembrall.parse_features(manifest_path)
    data = {
        "metadata": stats,
        "features": list(features.values())
    }
    return json.dumps(data, indent=2)
